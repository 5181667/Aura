export function getMentalAgeProfile(mentalAge: number): MentalAgeProfile {
  if (mentalAge < 18) return mentalAgeProfiles.child
  if (mentalAge < 25) return mentalAgeProfiles.young
  if (mentalAge < 36) return mentalAgeProfiles.mature
  if (mentalAge < 51) return mentalAgeProfiles.wise
  return mentalAgeProfiles.sage
}
