// MBTI 代表人物数据库
// 包含人物信息、简介和图片路径

export interface FamousPerson {
    id: string           // 唯一标识 (英文名下划线分隔)
    nameEn: string       // 英文名
    nameCn: string       // 中文名
    mbtiType: string     // MBTI类型
    bio: string          // 简介
    images: string[]     // 图片路径列表
}

// 从文件名解析人物信息的辅助函数
function createPerson(
    mbtiType: string,
    id: string,
    nameCn: string,
    bio: string,
    imageCount: number = 3
): FamousPerson {
    const nameEn = id.replace(/_/g, ' ')
    const images = Array.from({ length: imageCount }, (_, i) =>
        `/famous-people/${mbtiType}/${id}_${nameCn}_${i}.jpg`
    )
    return { id, nameEn, nameCn, mbtiType, bio, images }
}

